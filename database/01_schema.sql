CREATE DATABASE IF NOT EXISTS segurixt_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE segurixt_db;

CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 rol ENUM('ADMIN','EDITOR') NOT NULL DEFAULT 'EDITOR',
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categorias_servicio (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL,
 slug VARCHAR(150) NOT NULL UNIQUE,
 descripcion VARCHAR(500),
 icono VARCHAR(100),
 orden INT NOT NULL DEFAULT 0,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS servicios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 categoria_id BIGINT UNSIGNED NOT NULL,
 nombre VARCHAR(150) NOT NULL,
 slug VARCHAR(150) NOT NULL UNIQUE,
 descripcion_corta VARCHAR(500),
 descripcion TEXT,
 imagen_url VARCHAR(500),
 destacado BOOLEAN NOT NULL DEFAULT FALSE,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 orden INT NOT NULL DEFAULT 0,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_servicios_categoria FOREIGN KEY (categoria_id) REFERENCES categorias_servicio(id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categorias_producto (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 slug VARCHAR(120) NOT NULL UNIQUE,
 descripcion VARCHAR(500),
 orden INT NOT NULL DEFAULT 0,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS productos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 categoria_id BIGINT UNSIGNED NOT NULL,
 nombre VARCHAR(200) NOT NULL,
 slug VARCHAR(200) NOT NULL UNIQUE,
 marca VARCHAR(100),
 modelo VARCHAR(100),
 descripcion_corta VARCHAR(500),
 descripcion TEXT,
 precio DECIMAL(12,2),
 mostrar_precio BOOLEAN NOT NULL DEFAULT FALSE,
 destacado BOOLEAN NOT NULL DEFAULT FALSE,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT chk_producto_precio CHECK (precio IS NULL OR precio >= 0),
 CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias_producto(id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS imagenes_producto (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 producto_id BIGINT UNSIGNED NOT NULL,
 url VARCHAR(500) NOT NULL,
 texto_alt VARCHAR(255),
 principal BOOLEAN NOT NULL DEFAULT FALSE,
 orden INT NOT NULL DEFAULT 0,
 CONSTRAINT fk_imagenes_producto FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS promociones (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 titulo VARCHAR(200) NOT NULL,
 descripcion TEXT,
 imagen_url VARCHAR(500),
 fecha_inicio DATE,
 fecha_fin DATE,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT chk_promocion_fechas CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cotizaciones (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre_cliente VARCHAR(150) NOT NULL,
 telefono VARCHAR(30) NOT NULL,
 email VARCHAR(150),
 mensaje TEXT,
 estado ENUM('NUEVA','EN_REVISION','COTIZADA','ACEPTADA','RECHAZADA') NOT NULL DEFAULT 'NUEVA',
 fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS detalles_cotizacion (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 cotizacion_id BIGINT UNSIGNED NOT NULL,
 producto_id BIGINT UNSIGNED NULL,
 servicio_id BIGINT UNSIGNED NULL,
 cantidad INT UNSIGNED NOT NULL DEFAULT 1,
 observaciones VARCHAR(500),
 CONSTRAINT chk_detalle_cantidad CHECK (cantidad > 0),
 CONSTRAINT fk_detalle_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE,
 CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE RESTRICT,
 CONSTRAINT fk_detalle_servicio FOREIGN KEY (servicio_id) REFERENCES servicios(id) ON DELETE RESTRICT,
 CONSTRAINT chk_detalle_elemento CHECK ((producto_id IS NOT NULL AND servicio_id IS NULL) OR (producto_id IS NULL AND servicio_id IS NOT NULL))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS configuracion_empresa (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre_empresa VARCHAR(150) NOT NULL,
 descripcion TEXT,
 telefono VARCHAR(30),
 whatsapp VARCHAR(30),
 email VARCHAR(150),
 direccion VARCHAR(255),
 ciudad VARCHAR(100),
 estado VARCHAR(100),
 horario VARCHAR(255),
 facebook_url VARCHAR(500),
 instagram_url VARCHAR(500),
 fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
